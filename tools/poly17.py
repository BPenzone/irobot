#!/usr/bin/env python3
"""Write the POKEY's 17-bit polynomial as a C table (see src/common/pokey.c),
so that the 32X build can keep it in ROM instead of filling 16 KB of SDRAM.

Copyright 2026 the irobot 32X port authors. GPL-3.0-or-later, see LICENSE.

Usage: poly17.py OUT.h"""
import sys

SIZE = 131071
words = [0] * ((SIZE + 31) // 32)
p = 0
for i in range(SIZE):
    p = (p >> 1) + (~((p << 16) ^ (p << 11)) & 0x10000)
    if p & 0x100:
        words[i >> 5] |= 1 << (i & 31)
with open(sys.argv[1], 'w') as f:
    f.write('// Generated by tools/poly17.py.\n')
    f.write('static const uint32_t bit17[%d] = {\n' % len(words))
    for n in range(0, len(words), 8):
        f.write('    ' + ', '.join('0x%08X' % w for w in words[n:n + 8]) + ',\n')
    f.write('};\n')
